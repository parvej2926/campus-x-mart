export function translate(text, language) {
  if (language !== "bn" || typeof text !== "string") return text;
  if (!text.trim()) return text;
  const leading = text.match(/^\s*/)?.[0] || "";
  const trailing = text.match(/\s*$/)?.[0] || "";
  const content = text.slice(leading.length, text.length - trailing.length);
  let localized = translations.bn[content];
  if (!localized) {
    const greeting = content.match(/^Good (morning|afternoon|evening), (.+)\.$/);
    const resultRange = content.match(/^([\d,–-]+) of ([\d,]+)$/);
    const count = content.match(/^(\d+) (comments?|reviews?|orders?|reports?)$/);
    const reactionCount = content.match(/^(Like|Dislike) (\d+)$/);
    const orderUpdate = content.match(/^Order (.+)\.$/);
    const reportUpdate = content.match(/^Report (.+)\.$/);
    const ratingSummary = content.match(/^([\d.]+) · (\d+) reviews?$/);
    const sellerRating = content.match(/^Seller rating: (.+)$/);
    const sellerRatingValue = content.match(/^Seller ([\d.]+)$/);
    const ratePrompt = content.match(/^Rate (.+)$/);
    const noRatingSummary = content.match(/^No rating · (\d+) reviews?$/);
    const number = (value) => new Intl.NumberFormat("bn-BD").format(Number(value.replaceAll(",", "")));

    if (greeting) {
      localized = `${translations.bn[`Good ${greeting[1]}`]}, ${greeting[2] === "there" ? translations.bn.there : greeting[2]}.`;
    } else if (resultRange) {
      localized = `${number(resultRange[1])}–${number(resultRange[2])} এর মধ্যে`;
    } else if (count) {
      const unit = count[2].startsWith("comment") ? "টি মন্তব্য" : count[2].startsWith("review") ? "টি পর্যালোচনা" : count[2].startsWith("order") ? "টি অর্ডার" : "টি রিপোর্ট";
      localized = `${number(count[1])} ${unit}`;
    } else if (reactionCount) {
      localized = `${translations.bn[reactionCount[1]]} ${number(reactionCount[2])}`;
    } else if (orderUpdate) {
      localized = `অর্ডার ${translations.bn[orderUpdate[1]] || orderUpdate[1]}.`;
    } else if (reportUpdate) {
      localized = `রিপোর্ট ${translations.bn[reportUpdate[1]] || reportUpdate[1]}.`;
    } else if (ratingSummary) {
      localized = `${number(ratingSummary[1])} · ${number(ratingSummary[2])} টি পর্যালোচনা`;
    } else if (sellerRating) {
      localized = `বিক্রেতার রেটিং: ${sellerRating[1] === "No rating yet" ? "এখনও রেটিং নেই" : number(sellerRating[1])}`;
    } else if (sellerRatingValue) {
      localized = `বিক্রেতা ${number(sellerRatingValue[1])}`;
    } else if (noRatingSummary) {
      localized = `কোনো রেটিং নেই · ${number(noRatingSummary[1])} টি পর্যালোচনা`;
    } else if (ratePrompt) {
      localized = `রেট দিন: ${ratePrompt[1]}`;
    } else {
      localized = content;
    }
  }
  return `${leading}${localized}${trailing}`;
}

export function translateNotification(text, language) {
  if (language !== "bn" || typeof text !== "string") return text;
  const exact = notificationTitles[text];
  if (exact) return exact;

  const message = text.match(/^(.+) sent you a message\.$/);
  const comment = text.match(/^(.+) commented on (.+)\.$/);
  const purchaseRequest = text.match(/^(.+) requested (.+)\.$/);
  const meetupDate = text.match(/^(.+) meetup date: (.+)\.$/);
  const confirmed = text.match(/^Your request for (.+) was confirmed\.$/);
  const completed = text.match(/^Your purchase of (.+) is complete\.$/);
  const cancelled = text.match(/^The request for (.+) was cancelled\.$/);
  const reported = text.match(/^(.+) reported (.+)\.$/);

  if (message) return `${message[1]} আপনাকে একটি বার্তা পাঠিয়েছেন।`;
  if (comment) return `${comment[1]} ${comment[2]} পণ্যে মন্তব্য করেছেন।`;
  if (purchaseRequest) return `${purchaseRequest[1]} ${purchaseRequest[2]} কেনার অনুরোধ করেছেন।`;
  if (meetupDate) return `${meetupDate[1]} দেখা করার তারিখ: ${meetupDate[2]}.`;
  if (confirmed) return `${confirmed[1]} পণ্যের জন্য আপনার অনুরোধ নিশ্চিত হয়েছে।`;
  if (completed) return `${completed[1]} পণ্যের কেনাকাটা সম্পন্ন হয়েছে।`;
  if (cancelled) return `${cancelled[1]} পণ্যের অনুরোধ বাতিল হয়েছে।`;
  if (reported) return `${reported[1]} ${reported[2]} পণ্যটি রিপোর্ট করেছেন।`;
  return text;
}
